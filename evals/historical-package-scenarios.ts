const skill = (name: string) => `arturo-${name}`;
function task(
  id: string,
  domain: string[],
  prompt: string,
  check?: string,
  rubric?: string[],
  packages?: string[],
): Scenario {
  return {
    id,
    prompt,
    required: domain.map(skill),
    allowed: [...new Set([...domain, "language"])].map(skill),
    references: [],
    check,
    rubric,
    packages,
  };
}
